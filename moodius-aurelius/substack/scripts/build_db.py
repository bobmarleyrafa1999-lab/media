#!/usr/bin/env python3
"""Build the searchable editorial database from the CSV sources of truth (stdlib only).

Usage:
  python3 scripts/build_db.py                 # rebuild data/editorial.db + 03-backlog.md + vault notes
  python3 scripts/build_db.py search shame    # full-text search across topics and sources

Sources of truth (edit these, never the .db):
  data/editorial.csv   the ranked article backlog
  data/sources.csv     the research library (evidence tier, verification, URL)
"""
import csv
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "data" / "editorial.db"
WEIGHT = {1: 3, 2: 2, 3: 3, 4: 3, 5: 3, 6: 2, 7: 2, 8: 1, 9: 3, 10: 2}  # pillar weights, 01-editorial-strategy.md


def load(name):
    with open(ROOT / "data" / name, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def score(row):
    return 2 * int(row["relevance"]) + 2 * int(row["originality"]) + (6 - int(row["effort"]))


def rank(rows):
    for r in rows:
        r["score"] = str(score(r))
    rows.sort(key=lambda r: (-int(r["score"]), -WEIGHT[int(r["pillar_no"])], r["id"]))
    for i, r in enumerate(rows, 1):
        r["rank"] = str(i)
    return rows


def build():
    topics, sources = rank(load("editorial.csv")), load("sources.csv")
    with open(ROOT / "data" / "editorial.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(topics[0].keys()))
        w.writeheader()
        w.writerows(topics)
    DB.unlink(missing_ok=True)
    con = sqlite3.connect(DB)
    for table, rows in (("topics", topics), ("sources", sources)):
        cols = list(rows[0].keys())
        con.execute(f"CREATE TABLE {table} ({', '.join(c + ' TEXT' for c in cols)})")
        con.executemany(f"INSERT INTO {table} VALUES ({', '.join('?' * len(cols))})", [[r[c] for c in cols] for r in rows])
        fts_cols = [c + "_no" if c == "rank" else c for c in cols]  # "rank" is reserved in fts5
        con.execute(f"CREATE VIRTUAL TABLE {table}_fts USING fts5({', '.join(fts_cols)})")
        con.execute(f"INSERT INTO {table}_fts SELECT * FROM {table}")
    con.commit()
    con.close()
    write_backlog(topics, {s["id"]: s for s in sources})
    write_vault(topics, sources)
    print(f"{len(topics)} topics, {len(sources)} sources -> {DB.relative_to(ROOT)}, 03-backlog.md, vault/")


def write_backlog(topics, src):
    L = ["# 3. Ranked 50-article backlog", "",
         "*Generated by `scripts/build_db.py` from `data/editorial.csv`. Edit the CSV, then rebuild.*", "",
         "**Score** = 2 × relevance + 2 × originality + (6 − effort); max 25. Ties go to the higher-weighted pillar. "
         "Relevance and originality are editorial judgements (1–5) informed by `02-market-research.md`, not measured data. "
         "Effort: 1 = sources already verified in the library, 5 = new literature review needed.", "",
         "**Launch set:** the four drafted essays are not simply ranks 1–4. They are the strongest essay in four *different* pillars, "
         "chosen to show the publication's range in its first month: journaling (1), the shadow (2), masculinity (3) and money/status (10). "
         "Rank 3 (self-reliance) is partly covered inside rank 1, so it waits until month 3 as a follow-up; ranks 4 and 6 (Stoicism as regulation, shame vs guilt) "
         "open month 2 because Instagram already covers them heavily and they need the Substack less urgently.", "",
         "| Rank | ID | Pillar | Headline | Reader tension | Orig | Rel | Effort | Score | Status |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for t in topics:
        L.append(f"| {t['rank']} | {t['id']} | {t['pillar_no']} | {t['headline']} | {t['reader_tension']} | "
                 f"{t['originality']} | {t['relevance']} | {t['effort']} | **{t['score']}** | {t['status']} |")
    L += ["", "## Research and philosophy per topic", ""]
    for t in topics:
        refs = []
        for k in [x.strip() for x in t["research_ids"].split(";") if x.strip()]:
            s = src.get(k)
            if s:
                link = f" [link]({s['url']})" if s.get("url") else ""
                refs.append(f"{k} {s['author']} ({s['year']}), {s['evidence_tier']}{link}")
        L += [f"**{t['rank']}. {t['headline']}** ({t['id']}, {t['series']}). Philosophy: {t['philosophy']}. "
              f"Platforms: {t['platforms']}. Related: {t['related']}. Reusable: {t['reusable_assets'] or '—'}.",
              "", *[f"- {r}" for r in refs], ""]
    (ROOT / "03-backlog.md").write_text("\n".join(L), encoding="utf-8")


def write_vault(topics, sources):
    """One Obsidian note per topic and per source, with YAML front matter for Dataview."""
    for folder, rows, key in (("vault/20-ideas", topics, "id"), ("vault/10-sources", sources, "id")):
        d = ROOT / folder
        d.mkdir(parents=True, exist_ok=True)
        for r in rows:
            fm = "\n".join(f"{k}: \"{str(v).replace(chr(34), chr(39))}\"" for k, v in r.items())
            title = r.get("headline") or f"{r['author']} ({r['year']}): {r['concept']}"
            body = ""
            if folder.endswith("ideas"):
                links = " ".join(f"[[{x.strip()}]]" for x in r["research_ids"].split(";") if x.strip())
                body = f"\n**Tension:** {r['reader_tension']}\n\n**Sources:** {links}\n\n**Related:** " + \
                       " ".join(f"[[{x.strip()}]]" for x in r["related"].split(";") if x.strip()) + "\n"
            else:
                body = f"\n**Finding:** {r['key_finding']}\n\n**Caveat:** {r['caveat']}\n\n**Angle:** {r['content_angle']}\n"
            (d / f"{r[key]}.md").write_text(f"---\n{fm}\n---\n# {title}\n{body}", encoding="utf-8")


def search(q):
    con = sqlite3.connect(DB)
    for table, cols in (("topics", "rank_no, id, headline"), ("sources", "id, author, year, concept")):
        rows = con.execute(f"SELECT {cols} FROM {table}_fts WHERE {table}_fts MATCH ? LIMIT 15", (q,)).fetchall()
        print(f"== {table} ({len(rows)})")
        for r in rows:
            print("  ", " | ".join(r))


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "search":
        search(" ".join(sys.argv[2:]))
    else:
        build()
